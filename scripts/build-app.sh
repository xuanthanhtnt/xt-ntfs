#!/usr/bin/env bash
# Builds "XT NTFS.app" (universal) from the Swift package and the prebuilt
# engine, signs it ad-hoc and verifies the bundle.
#
#   scripts/build-app.sh <engine-bin-dir> [output-dir]
#
# Environment:
#   XT_BUILD_NUMBER     CFBundleVersion (default: git commit count)
#   XT_ARCHS            default "arm64 x86_64"
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENGINE="${1:?usage: build-app.sh <engine-bin-dir> [output-dir]}"
OUT="${2:-$ROOT/build}"
VERSION="$(tr -d '[:space:]' < "$ROOT/VERSION")"
BUILD="${XT_BUILD_NUMBER:-$(git -C "$ROOT" rev-list --count HEAD 2>/dev/null || echo 1)}"
ARCHS="${XT_ARCHS:-arm64 x86_64}"
PUBKEY="$(tr -d '[:space:]' < "$ROOT/Resources/sparkle_public_key.txt")"
APP="$OUT/XT NTFS.app"

log() { printf '\033[1;34m==>\033[0m %s\n' "$*"; }

[ -x "$ENGINE/ntfs-3g" ] || { echo "engine binaries not found in $ENGINE" >&2; exit 1; }

# Stamp the version into the shared module for this build only.
INFO_SWIFT="$ROOT/Sources/XTShared/BuildInfo.swift"
cp "$INFO_SWIFT" "$INFO_SWIFT.orig"
trap 'mv -f "$INFO_SWIFT.orig" "$INFO_SWIFT"' EXIT
cat > "$INFO_SWIFT" <<EOF
// Generated by scripts/build-app.sh
public enum XTBuild {
    public static let version = "$VERSION"
    public static let build = "$BUILD"
    public static var fullVersion: String { "\(version) (\(build))" }
}
EOF

ARCH_ARGS=()
for a in $ARCHS; do ARCH_ARGS+=(--arch "$a"); done

log "Building XT NTFS $VERSION ($BUILD) for $ARCHS"
cd "$ROOT"
swift build -c release "${ARCH_ARGS[@]}"
BIN="$(swift build -c release "${ARCH_ARGS[@]}" --show-bin-path)"
log "Products in $BIN"

rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources/engine" "$APP/Contents/Resources/scripts" \
         "$APP/Contents/Frameworks"

cp "$BIN/XTNTFS" "$APP/Contents/MacOS/XTNTFS"
cp "$BIN/xtntfsd" "$APP/Contents/MacOS/xtntfsd"

# Sparkle.framework (binary target): products dir, or the downloaded artifact.
FW="$(find "$BIN" -maxdepth 2 -name Sparkle.framework -type d | head -1)"
if [ -z "$FW" ]; then
  FW="$(find "$ROOT/.build/artifacts" -path '*macos*' -name Sparkle.framework -type d | head -1)"
fi
[ -n "$FW" ] || { echo "Sparkle.framework not found" >&2; exit 1; }
ditto "$FW" "$APP/Contents/Frameworks/Sparkle.framework"
if ! otool -l "$APP/Contents/MacOS/XTNTFS" | grep -q "@executable_path/../Frameworks"; then
  install_name_tool -add_rpath "@executable_path/../Frameworks" "$APP/Contents/MacOS/XTNTFS"
fi

sed -e "s/__VERSION__/$VERSION/" -e "s/__BUILD__/$BUILD/" -e "s#__SPARKLE_PUBLIC_KEY__#$PUBKEY#" \
  "$ROOT/Resources/Info.plist" > "$APP/Contents/Info.plist"
plutil -lint "$APP/Contents/Info.plist"
printf 'APPL????' > "$APP/Contents/PkgInfo"

cp "$ROOT/Resources/AppIcon.icns" "$ROOT/Resources/NTFSVolume.icns" "$APP/Contents/Resources/"
cp -R "$ROOT/Resources/en.lproj" "$ROOT/Resources/vi.lproj" "$APP/Contents/Resources/"
for f in "$APP/Contents/Resources/"*.lproj/Localizable.strings; do plutil -lint "$f"; done
cp "$ROOT/Resources/scripts/"*.sh "$APP/Contents/Resources/scripts/"
chmod 755 "$APP/Contents/Resources/scripts/"*.sh
cp "$ENGINE"/* "$APP/Contents/Resources/engine/"
cp "$ROOT/LICENSE" "$APP/Contents/Resources/LICENSE.txt"

# A fixed signing identity keeps the code requirement stable across
# updates, so macOS privacy grants (Full Disk Access for the helper) survive
# them. Without one the bundle is signed ad hoc.
SIGN="${XT_SIGN_IDENTITY:--}"
log "Signing (${XT_SIGN_IDENTITY:-ad hoc})"
for f in "$APP/Contents/Resources/engine/"*; do
  if file "$f" | grep -q "Mach-O"; then
    codesign --force --sign "$SIGN" --timestamp=none "$f"
  fi
done
SFW="$APP/Contents/Frameworks/Sparkle.framework"
for x in "$SFW"/Versions/B/XPCServices/*.xpc; do
  [ -e "$x" ] && codesign --force --sign "$SIGN" --timestamp=none "$x"
done
[ -e "$SFW/Versions/B/Autoupdate" ] && codesign --force --sign "$SIGN" --timestamp=none "$SFW/Versions/B/Autoupdate"
[ -e "$SFW/Versions/B/Updater.app" ] && codesign --force --sign "$SIGN" --timestamp=none "$SFW/Versions/B/Updater.app"
codesign --force --sign "$SIGN" --timestamp=none "$SFW"
codesign --force --sign "$SIGN" --timestamp=none --identifier com.xuanthanhtnt.xtntfs.helper "$APP/Contents/MacOS/xtntfsd"
codesign --force --sign "$SIGN" --timestamp=none "$APP"
codesign --verify --deep --strict --verbose=2 "$APP"

log "Bundle contents"
lipo -info "$APP/Contents/MacOS/XTNTFS" "$APP/Contents/MacOS/xtntfsd" "$APP/Contents/Resources/engine/ntfs-3g"
"$APP/Contents/MacOS/xtntfsd" --version
du -sh "$APP"
log "Built $APP"
